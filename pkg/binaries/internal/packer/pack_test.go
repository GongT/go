package packer

import (
	"bytes"
	"testing"

	"github.com/gongt/go/internal/myenv"
	"github.com/gongt/go/pkg/binaries/internal/endian"
	"github.com/stretchr/testify/require"
)

func TestPackMatchesNativeEndianBytes(t *testing.T) {
	myenv.T(t)

	stream := bytes.Buffer{}
	packer := NewPack(&stream, endian.LittleEndian)

	packer.WriteBytes([]byte{0xaa, 0xbb})
	packer.WriteString("go")
	packer.WriteUint(0x0102030405060708)
	packer.WriteUint64(0x1112131415161718)
	packer.WriteUint32(0x21222324)
	packer.WriteUint16(0x3132)
	packer.WriteBool(true)
	packer.WriteUint8(0x42)
	packer.WriteInt(-2)
	packer.WriteInt64(-3)
	packer.WriteInt32(-4)
	packer.WriteInt16(-5)
	packer.WriteInt8(-6)
	packer.WriteFloat64(-2.5)
	packer.WriteFloat32(1.5)

	expected := []byte{
		0xaa, 0xbb, 'g', 'o',
		0x08, 0x07, 0x06, 0x05, 0x04, 0x03, 0x02, 0x01,
		0x18, 0x17, 0x16, 0x15, 0x14, 0x13, 0x12, 0x11,
		0x24, 0x23, 0x22, 0x21,
		0x32, 0x31,
		0x01, 0x42,
		0xfe, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xfd, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xfc, 0xff, 0xff, 0xff,
		0xfb, 0xff,
		0xfa,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0xc0,
		0x00, 0x00, 0xc0, 0x3f,
	}
	require.Equal(t, expected, stream.Bytes())
	require.Equal(t, true, packer.IsBuffered())
}
